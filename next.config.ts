import type { NextConfig } from "next";

/**
 * Security headers applied to every route. A strict nonce-based
 * Content-Security-Policy is planned (see docs/SECURITY_MODEL.md); for now we
 * set the directives that cannot break Next.js inline bootstrapping.
 */
const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(self), microphone=(), geolocation=(), payment=()" },
  { key: "Content-Security-Policy", value: "frame-ancestors 'none'; base-uri 'self'; form-action 'self'; object-src 'none'" },
  ...(process.env.NODE_ENV === "production"
    ? [{ key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" }]
    : []),
];

const nextConfig: NextConfig = {
  // ADR-003 (docs/ARCHITECTURE.md): Cache Components disabled. Nearly every
  // page is per-tenant, per-user data; request-time rendering is simpler and
  // removes the risk of caching one tenant's data for another.
  cacheComponents: false,
  poweredByHeader: false,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
